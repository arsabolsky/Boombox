
-- ============================================
-- BOOMBOX DATABASE SCHEMA
-- ============================================

-- CLIENTS
-- Stores registered Boombox endpoint information.

CREATE TABLE clients (
    client_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    hostname TEXT NOT NULL,
    os TEXT,
    os_version TEXT,
    agent_version TEXT,
    system_information JSONB NOT NULL DEFAULT '{}'::jsonb,
    registered_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_seen_at TIMESTAMPTZ,
    last_poll_at TIMESTAMPTZ,
    status TEXT NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'disabled'))
);


-- EVENTS
-- Stores security events generated by clients.

CREATE TABLE events (
    id BIGSERIAL PRIMARY KEY,
    client_id UUID NOT NULL,
    timestamp TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    event_type TEXT NOT NULL,
    raw_data JSONB NOT NULL,

    CONSTRAINT fk_events_client
        FOREIGN KEY (client_id)
        REFERENCES clients(client_id)
        ON DELETE CASCADE,

    UNIQUE (id, client_id)
);


-- REMEDIATIONS
-- Stores AI-generated remediation recommendations.

CREATE TABLE remediations (
    id BIGSERIAL PRIMARY KEY,
    client_id UUID NOT NULL,
    event_id BIGINT NOT NULL,
    title TEXT NOT NULL,
    summary TEXT,
    proposed_script TEXT,
    severity TEXT,
    status TEXT NOT NULL DEFAULT 'pending_review'
        CHECK (status IN (
            'pending_review',
            'approved',
            'denied',
            'executed',
            'failed'
        )),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    reviewed_at TIMESTAMPTZ,
    reviewed_by TEXT,

    CONSTRAINT fk_remediations_event_client
        FOREIGN KEY (event_id, client_id)
        REFERENCES events(id, client_id)
        ON DELETE CASCADE
);


-- CLIENT QUERIES
-- Stores security queries assigned to individual clients.

CREATE TABLE client_queries (
    query_id BIGSERIAL PRIMARY KEY,
    client_id UUID NOT NULL,
    query_name TEXT NOT NULL,
    query_configuration JSONB NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    version INTEGER NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_client_queries_client
        FOREIGN KEY (client_id)
        REFERENCES clients(client_id)
        ON DELETE CASCADE,

    CONSTRAINT unique_client_query
        UNIQUE (client_id, query_name)
);


-- ============================================
-- INDEXES
-- ============================================

CREATE INDEX idx_events_client_timestamp
    ON events(client_id, timestamp DESC);

CREATE INDEX idx_remediations_client_status
    ON remediations(client_id, status);

CREATE INDEX idx_remediations_created_at
    ON remediations(created_at DESC);

CREATE INDEX idx_client_queries_client
    ON client_queries(client_id, enabled);

